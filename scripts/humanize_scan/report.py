"""Filesystem scan, aggregation, and report rendering."""

from __future__ import annotations

import fnmatch
import json
import os
import re
import time
from datetime import datetime, timezone
from pathlib import Path

from . import __version__
from .core import (
    DEFAULT_LINE_LIMITS, DEFAULT_SKIP_DIRS, EXT_LANG, SKIP_FILE_PATTERNS,
    FileAnalyzer,
)

LANG_ALIASES = {
    "py": "python", "python": "python",
    "js": "javascript", "javascript": "javascript", "ts": "javascript",
    "typescript": "javascript", "jsx": "javascript", "tsx": "javascript",
    "php": "php",
    "c": "c",
    "cpp": "cpp", "c++": "cpp", "cxx": "cpp",
    "java": "java",
    "generic": "generic", "other": "generic",
}
ALL_LANGS = {"python", "javascript", "php", "c", "cpp", "java", "generic"}


def parse_languages(value: str) -> set[str]:
    if not value or value.strip().lower() == "all":
        return set(ALL_LANGS)
    result: set[str] = set()
    for item in value.split(","):
        item = item.strip().lower()
        if not item:
            continue
        if item not in LANG_ALIASES:
            raise ValueError(f"unknown language: {item}")
        result.add(LANG_ALIASES[item])
    return result or set(ALL_LANGS)


def parse_excludes(value: str) -> list[str]:
    return [p.strip().replace("\\", "/") for p in value.split(",") if p.strip()]


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def detect_line_limits(root: Path) -> dict[str, int]:
    limits = dict(DEFAULT_LINE_LIMITS)
    editorconfig = _read_text(root / ".editorconfig")
    match = re.search(r"(?im)^\s*max_line_length\s*=\s*(\d+)", editorconfig)
    if match:
        for key in limits:
            limits[key] = int(match.group(1))

    pyproject = _read_text(root / "pyproject.toml")
    for pattern in (r"(?im)^\s*line-length\s*=\s*(\d+)", r"(?im)^\s*max-line-length\s*=\s*(\d+)"):
        match = re.search(pattern, pyproject)
        if match:
            limits["python"] = int(match.group(1))
            break

    for name in ("setup.cfg", ".flake8", "tox.ini"):
        text = _read_text(root / name)
        match = re.search(r"(?im)^\s*max-line-length\s*=\s*(\d+)", text)
        if match:
            limits["python"] = int(match.group(1))
            break

    prettier = ""
    for name in (".prettierrc", ".prettierrc.json", ".prettierrc.js", "prettier.config.js", "package.json"):
        prettier += _read_text(root / name)
    match = re.search(r"(?im)[\"']?printWidth[\"']?\s*[:=]\s*(\d+)", prettier)
    if match:
        limits["javascript"] = int(match.group(1))

    clang = _read_text(root / ".clang-format")
    match = re.search(r"(?im)^\s*ColumnLimit\s*:\s*(\d+)", clang)
    if match:
        limits["c"] = limits["cpp"] = int(match.group(1))

    checkstyle = _read_text(root / "checkstyle.xml")
    match = re.search(r"(?is)LineLength.*?value=[\"'](\d+)[\"']", checkstyle)
    if match:
        limits["java"] = int(match.group(1))
    return limits


def detect_formatter(root: Path) -> bool:
    names = (
        ".editorconfig", ".prettierrc", ".prettierrc.json", ".prettierrc.js",
        "prettier.config.js", ".clang-format", ".clang-tidy", ".flake8",
        "phpcs.xml", "phpcs.xml.dist", ".php-cs-fixer.php", "checkstyle.xml",
        ".rustfmt.toml", "rustfmt.toml",
    )
    if any((root / name).exists() for name in names):
        return True
    pyproject = _read_text(root / "pyproject.toml").lower()
    if "[tool.black]" in pyproject or "[tool.ruff]" in pyproject or "[tool.isort]" in pyproject:
        return True
    package = _read_text(root / "package.json").lower()
    return "prettier" in package or "eslint" in package


def _excluded(rel: str, name: str, patterns: list[str]) -> bool:
    parts = rel.split("/")
    for pattern in patterns:
        if fnmatch.fnmatch(rel, pattern) or fnmatch.fnmatch(name, pattern):
            return True
        if pattern in parts:
            return True
    return False


def _skip_file(name: str, rel: str) -> bool:
    lower = name.lower()
    if any(fnmatch.fnmatch(lower, pattern) for pattern in SKIP_FILE_PATTERNS):
        return True
    if lower in {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock"}:
        return True
    return False


def _is_generated(text: str) -> bool:
    head = text[:2048].lower()
    markers = (
        "do not edit", "auto-generated", "autogenerated", "generated by",
        "@generated", "code generated", "this file is generated",
    )
    return any(marker in head for marker in markers)


def _is_binary(data: bytes) -> bool:
    return b"\x00" in data[:4096]


def _iter_candidates(
    root: Path,
    languages: set[str],
    excludes: list[str],
    max_file_size_kb: int,
):
    for dirpath, dirnames, filenames in os.walk(root):
        current = Path(dirpath)
        rel_dir = current.relative_to(root).as_posix()
        if rel_dir == ".":
            rel_dir = ""
        kept_dirs = []
        for dirname in dirnames:
            if dirname in DEFAULT_SKIP_DIRS:
                continue
            rel = f"{rel_dir}/{dirname}".strip("/")
            if _excluded(rel, dirname, excludes):
                continue
            kept_dirs.append(dirname)
        dirnames[:] = kept_dirs

        for filename in filenames:
            path = current / filename
            if path.is_symlink():
                continue
            rel = f"{rel_dir}/{filename}".strip("/")
            if _skip_file(filename, rel):
                continue
            if _excluded(rel, filename, excludes):
                continue
            lang = EXT_LANG.get(path.suffix.lower())
            if lang is None or lang not in languages:
                continue
            try:
                size = path.stat().st_size
            except OSError:
                continue
            if size > max_file_size_kb * 1024:
                yield path, rel, lang, "size"
                continue
            yield path, rel, lang, ""


def _language_summary(files: list[dict]) -> dict:
    summary: dict[str, dict] = {}
    for item in files:
        lang = item["language"]
        entry = summary.setdefault(lang, {
            "files": 0, "loc": 0, "score_weighted": 0.0,
            "ai": 0, "mixed": 0, "human": 0,
        })
        entry["files"] += 1
        entry["loc"] += item["loc"]
        entry["score_weighted"] += item["score"] * item["loc"]
        if item["class"] == "ai-shaped":
            entry["ai"] += 1
        elif item["class"] == "mixed":
            entry["mixed"] += 1
        else:
            entry["human"] += 1
    result = {}
    for lang, entry in summary.items():
        loc = entry["loc"]
        result[lang] = {
            "files": entry["files"],
            "loc": loc,
            "score": round(entry["score_weighted"] / loc, 1) if loc else 0.0,
            "ai": entry["ai"],
            "mixed": entry["mixed"],
            "human": entry["human"],
        }
    return result


def _aggregate_rules(files: list[dict], positive: bool) -> list[dict]:
    stats: dict[str, dict] = {}
    for item in files:
        for finding in item["findings"]:
            weight = finding["weight"]
            if (positive and weight <= 0) or (not positive and weight >= 0):
                continue
            points = weight * min(finding["count"], finding["cap"])
            entry = stats.setdefault(finding["rule"], {
                "rule": finding["rule"], "category": finding["category"],
                "points": 0.0, "files": set(), "sample": "", "message": finding["message"],
                "risk": finding["risk"],
            })
            entry["points"] += points
            entry["files"].add(item["path"])
            if not entry["sample"] and finding["samples"]:
                entry["sample"] = finding["samples"][0]
    rows = []
    for entry in stats.values():
        rows.append({
            "rule": entry["rule"], "category": entry["category"],
            "points": round(abs(entry["points"]), 1),
            "files": len(entry["files"]), "sample": entry["sample"],
            "message": entry["message"], "risk": entry["risk"],
        })
    rows.sort(key=lambda x: (-x["points"], x["rule"]))
    return rows[:15]


def _top_signals(item: dict, limit: int = 3) -> str:
    signals = [
        f["rule"] for f in item["findings"]
        if f["weight"] != 0 and f["count"] > 0
    ][:limit]
    return ", ".join(signals) if signals else "none"


def scan_path(
    root: Path,
    languages: set[str] | None = None,
    excludes: list[str] | None = None,
    max_file_size_kb: int = 1024,
) -> dict:
    root = root.resolve()
    languages = languages or set(ALL_LANGS)
    excludes = excludes or []
    scan_root = root.parent if root.is_file() else root
    limits = detect_line_limits(scan_root)
    has_formatter = detect_formatter(scan_root)
    started = time.time()
    files: list[dict] = []
    errors: list[dict] = []
    skipped: list[dict] = []

    if root.is_file():
        candidates = [(root, root.name, EXT_LANG.get(root.suffix.lower()), "")]
    else:
        candidates = _iter_candidates(scan_root, languages, excludes, max_file_size_kb)

    seen: set[Path] = set()
    for path, rel, lang, skip_reason in candidates:
        if path in seen:
            continue
        seen.add(path)
        if skip_reason:
            skipped.append({"path": rel, "reason": skip_reason})
            continue
        if lang is None or lang not in languages:
            continue
        try:
            data = path.read_bytes()
        except OSError as exc:
            errors.append({"path": rel, "error": str(exc)})
            continue
        if _is_binary(data):
            skipped.append({"path": rel, "reason": "binary"})
            continue
        text = data.decode("utf-8-sig", errors="replace")
        if _is_generated(text):
            skipped.append({"path": rel, "reason": "generated"})
            continue
        line_limit = limits.get(lang, DEFAULT_LINE_LIMITS.get(lang, 100))
        try:
            report = FileAnalyzer(
                str(path), rel, text, lang, line_limit, has_formatter,
            ).analyze()
        except Exception as exc:  # keep scanning after one bad file
            errors.append({"path": rel, "error": f"{type(exc).__name__}: {exc}"})
            continue
        files.append(report)

    files.sort(key=lambda item: (-item["score"], item["path"]))
    total_loc = sum(item["loc"] for item in files)
    if total_loc:
        weighted_score = sum(item["score"] * item["loc"] for item in files) / total_loc
        weighted_conf = sum(item["confidence"] * item["loc"] for item in files) / total_loc
    else:
        weighted_score = 50.0
        weighted_conf = 0.0
    counts = {"ai-shaped": 0, "mixed": 0, "human-shaped": 0}
    for item in files:
        counts[item["class"]] += 1
    if total_loc == 0:
        klass = "mixed"
    elif weighted_score >= 68:
        klass = "ai-shaped"
    elif weighted_score >= 45:
        klass = "mixed"
    else:
        klass = "human-shaped"

    ai_files = [item for item in files if item["class"] == "ai-shaped"][:20]
    human_files = [item for item in files if item["class"] == "human-shaped"][:10]
    summary = {
        "files": len(files),
        "loc": total_loc,
        "score": round(weighted_score, 1),
        "class": klass,
        "confidence": round(weighted_conf, 2),
        "ai_shaped": counts["ai-shaped"],
        "mixed": counts["mixed"],
        "human_shaped": counts["human-shaped"],
        "skipped": len(skipped),
        "errors": len(errors),
        "duration_seconds": round(time.time() - started, 2),
    }
    return {
        "tool": "humanize-code",
        "version": __version__,
        "root": str(root),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "options": {
            "languages": sorted(languages),
            "excludes": excludes,
            "max_file_size_kb": max_file_size_kb,
            "has_formatter": has_formatter,
        },
        "line_limits": limits,
        "summary": summary,
        "languages": _language_summary(files),
        "top_ai_rules": _aggregate_rules(files, positive=True),
        "top_human_rules": _aggregate_rules(files, positive=False),
        "ai_files": [{"path": f["path"], "score": f["score"], "signals": _top_signals(f)} for f in ai_files],
        "human_files": [{"path": f["path"], "score": f["score"], "signals": _top_signals(f)} for f in human_files],
        "files": files,
        "skipped_samples": skipped[:30],
        "errors": errors,
    }


def _md(value: object) -> str:
    return str(value).replace("|", "\\|").replace("`", "'")


def _score_line(item: dict) -> str:
    return (
        f"| `{_md(item['path'])}` | {item['score']:.1f} | {item['class']} | "
        f"{item['confidence']:.2f} | {item['loc']} | {_md(_top_signals(item))} |"
    )


def render_markdown(scan: dict) -> str:
    summary = scan["summary"]
    lines = [
        "# Humanize Code scan",
        "",
        f"**Root:** `{_md(scan['root'])}`  ",
        f"**Generated:** {scan['generated_at']}  ",
        f"**Scanner:** humanize-code {scan['version']}",
        "",
        "> This is a heuristic style report, not proof of authorship and not a",
        "> guarantee about AI detectors. Legacy findings are evidence and cleanup",
        "> candidates, not patterns to add.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Files scanned | {summary['files']} |",
        f"| Lines of code | {summary['loc']} |",
        f"| Overall score | {summary['score']:.1f} / 100 |",
        f"| Class | {summary['class']} |",
        f"| Confidence | {summary['confidence']:.2f} |",
        f"| AI-shaped files | {summary['ai_shaped']} |",
        f"| Mixed files | {summary['mixed']} |",
        f"| Human-shaped files | {summary['human_shaped']} |",
        f"| Skipped | {summary['skipped']} |",
        f"| Scan errors | {summary['errors']} |",
        f"| Duration | {summary['duration_seconds']}s |",
        "",
        "## Languages",
        "",
        "| Language | Files | LOC | Score | AI | Mixed | Human |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for lang, item in sorted(scan["languages"].items(), key=lambda kv: -kv[1]["loc"]):
        lines.append(
            f"| {_md(lang)} | {item['files']} | {item['loc']} | {item['score']:.1f} | "
            f"{item['ai']} | {item['mixed']} | {item['human']} |"
        )

    lines += ["", "## Strongest AI-style signals", ""]
    if scan["top_ai_rules"]:
        lines += [
            "| Rule | Category | Files | Points | Evidence |",
            "| --- | --- | ---: | ---: | --- |",
        ]
        for row in scan["top_ai_rules"]:
            evidence = f"`{_md(row['sample'])}`" if row["sample"] else row["message"]
            lines.append(
                f"| `{_md(row['rule'])}` | {_md(row['category'])} | {row['files']} | "
                f"{row['points']:.1f} | {evidence} |"
            )
    else:
        lines.append("No AI-positive signals found.")

    lines += ["", "## Strongest human-style signals", ""]
    if scan["top_human_rules"]:
        lines += [
            "| Rule | Category | Files | Points | Evidence |",
            "| --- | --- | ---: | ---: | --- |",
        ]
        for row in scan["top_human_rules"]:
            evidence = f"`{_md(row['sample'])}`" if row["sample"] else row["message"]
            lines.append(
                f"| `{_md(row['rule'])}` | {_md(row['category'])} | {row['files']} | "
                f"{row['points']:.1f} | {evidence} |"
            )
    else:
        lines.append("No human-negative signals found.")

    lines += [
        "", "## Files to inspect first", "",
        "| File | Score | Class | Confidence | LOC | Top signals |",
        "| --- | ---: | --- | ---: | ---: | --- |",
    ]
    for item in scan["files"][:50]:
        lines.append(_score_line(item))

    if scan["ai_files"]:
        lines += ["", "## AI-shaped files", ""]
        for item in scan["ai_files"]:
            lines.append(f"- `{_md(item['path'])}` — {item['score']:.1f} — {_md(item['signals'])}")

    if scan["human_files"]:
        lines += ["", "## Human-shaped files (use as style evidence)", ""]
        for item in scan["human_files"]:
            lines.append(f"- `{_md(item['path'])}` — {item['score']:.1f} — {_md(item['signals'])}")

    if scan["files"]:
        lines += ["", "## Evidence for the strongest AI-shaped files", ""]
        for item in scan["ai_files"][:10]:
            lines += [
                f"### `{_md(item['path'])}`",
                "",
                f"Score {item['score']:.1f} · confidence {_md(next((f['confidence'] for f in scan['files'] if f['path'] == item['path']), ''))}",
                "",
                "| Rule | Count | Weight | Evidence |",
                "| --- | ---: | ---: | --- |",
            ]
            findings = [
                f for f in next((x["findings"] for x in scan["files"] if x["path"] == item["path"]), [])
                if f["weight"] != 0
            ][:8]
            for finding in findings:
                sample = finding["samples"][0] if finding["samples"] else finding["message"]
                lines.append(
                    f"| `{_md(finding['rule'])}` | {finding['count']} | {finding['weight']:+d} | "
                    f"`{_md(sample)}` |"
                )
            lines.append("")

    if scan["skipped_samples"]:
        lines += ["", "## Skipped samples", "", "| Path | Reason |", "| --- | --- |"]
        for item in scan["skipped_samples"]:
            lines.append(f"| `{_md(item['path'])}` | {_md(item['reason'])} |")

    if scan["errors"]:
        lines += ["", "## Scan errors", "", "| Path | Error |", "| --- | --- |"]
        for item in scan["errors"][:20]:
            lines.append(f"| `{_md(item['path'])}` | {_md(item['error'])} |")

    lines += [
        "",
        "## Notes",
        "",
        "- Scores are weighted by lines of code and shrink toward 50 for small files.",
        "- Formatting signals are weak; formatters make human code look uniform too.",
        "- A `human-shaped` score is not proof a person wrote the file.",
        "- Legacy/high-risk findings need a separate migration with tests.",
        "- Next step: read the cited evidence, build a house-style profile, and",
        "  fill `templates/STYLE_REPORT.md` before applying any rewrite.",
        "",
    ]
    return "\n".join(lines)


def write_reports(scan: dict, out_dir: Path, json_only: bool = False) -> tuple[Path, Path | None]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "scan.json"
    json_path.write_text(json.dumps(scan, ensure_ascii=False, indent=2), encoding="utf-8")
    if json_only:
        return json_path, None
    md_path = out_dir / "scan.md"
    md_path.write_text(render_markdown(scan), encoding="utf-8")
    return json_path, md_path
